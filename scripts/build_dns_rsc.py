#!/usr/bin/env python3
"""Build lists/dns.rsc from dns/vpn.txt.

It creates DNS forwarder VPN if the router has none (an existing one is left
as is), routes the forwarder's DNS servers through routing table VPN
(/routing rule, added only if missing), applies /ip dns settings and adds ad-block lists (/ip dns adlist)
that are not on the router yet; adlists are never removed by this script.

Every domain becomes a MikroTik static DNS entry:
  /ip dns static add name=<domain> type=FWD forward-to=VPN
      match-subdomain=yes address-list=VPN

The generated script syncs /ip dns static: entries with comment prefix
"proxy_rules: " belong to this repository; an existing FWD entry with the
same name is taken over (its settings are replaced); other entries are kept.

Exits with code 1 and writes nothing if dns/vpn.txt has an invalid line.
"""
import pathlib
import re
import sys

FORWARDER = "VPN"
ADDRESS_LIST = "VPN"
COMMENT = "proxy_rules: dns"
STALE_COMMENT = "proxy_rules: stale"

# /ip dns forwarders add name=VPN ... (only if missing)
FORWARDER_SETTINGS = {
    "dns-servers": "1.1.1.1,8.8.8.8",
    "doh-servers": "https://dns.google/dns-query,https://1.1.1.1/dns-query",
    "verify-doh-cert": "no",
}

# /routing rule add action=lookup dst-address=... table=VPN (only if missing).
# Routing table VPN is created if missing; with action=lookup an empty table
# falls back to main, so nothing breaks before the VPN route exists.
ROUTING_TABLE = "VPN"
ROUTED_DNS = ["1.1.1.1/32", "8.8.8.8/32"]

# /ip dns set ...
DNS_SETTINGS = {
    "address-list-extra-time": "1d",
    "allow-remote-requests": "yes",
    "cache-size": "24576KiB",
}

# /ip dns adlist add url=... ssl-verify=no (added only if the url is missing)
ADLISTS = [
    "https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts",
    "https://adguardteam.github.io/HostlistsRegistry/assets/filter_1.txt",
]

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "dns" / "vpn.txt"
OUT = ROOT / "lists" / "dns.rsc"

LABEL = r"(?!-)[a-z0-9_-]{1,63}(?<!-)"
DOMAIN = re.compile(rf"^(?=.{{1,253}}$)(?:{LABEL}\.)+{LABEL}$")


def read_domains(path: pathlib.Path) -> list[str]:
    domains: list[str] = []
    errors = []
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip().lower().rstrip(".")
        if not line:
            continue
        if line.startswith("*."):
            line = line[2:]
        try:
            line = line.encode("idna").decode("ascii")
        except UnicodeError:
            pass
        if not DOMAIN.match(line):
            errors.append(f"{path.name}:{lineno}: invalid domain {raw.strip()!r}")
            continue
        domains.append(line)
    if errors:
        raise ValueError("\n".join(errors))
    return domains


def drop_covered(domains: list[str]) -> tuple[list[str], list[str]]:
    # match-subdomain=yes on a parent already covers its subdomains.
    unique = list(dict.fromkeys(domains))
    names = set(unique)
    kept, dropped = [], []
    for d in unique:
        parts = d.split(".")
        if any(".".join(parts[i:]) in names for i in range(1, len(parts) - 1)):
            dropped.append(d)
        else:
            kept.append(d)
    return kept, dropped


def render(domains: list[str]) -> str:
    ds = "/ip dns static"
    params = (f"type=FWD forward-to={FORWARDER} match-subdomain=yes "
              f"address-list={ADDRESS_LIST} disabled=no comment=\"{COMMENT}\"")
    lines = [
        "# Generated by scripts/build_dns_rsc.py from dns/vpn.txt - do not edit by hand.",
        "# Entries with comment prefix \"proxy_rules: \" are owned by this script;",
        "# a FWD entry with the same name is taken over, other entries are kept.",
        f':if ([:len [/ip dns forwarders find where name="{FORWARDER}"]] = 0) do={{ '
        f'/ip dns forwarders add name={FORWARDER} '
        + " ".join(f'{k}="{v}"' for k, v in FORWARDER_SETTINGS.items()) + " }",
        f':if ([:len [/routing table find where name="{ROUTING_TABLE}"]] = 0) do={{ '
        f'/routing table add name={ROUTING_TABLE} fib }}',
    ] + [
        f':if ([:len [/routing rule find dst-address={net} table={ROUTING_TABLE}]] = 0) do={{ '
        f'/routing rule add action=lookup disabled=no dst-address={net} table={ROUTING_TABLE} }}'
        for net in ROUTED_DNS
    ] + [
        "/ip dns set " + " ".join(f"{k}={v}" for k, v in DNS_SETTINGS.items()),
    ]
    for url in ADLISTS:
        lines.append(
            f':if ([:len [/ip dns adlist find where url="{url}"]] = 0) do={{ '
            f'/ip dns adlist add url="{url}" ssl-verify=no }}'
        )
    lines.append(
        f'{ds} set [find where type=FWD comment~"^proxy_rules: "] comment="{STALE_COMMENT}"')
    for d in domains:
        lines.append(
            f':if ([:len [{ds} find where type=FWD name="{d}"]] = 0) do={{ '
            f'{ds} add name="{d}" {params} }} else={{ '
            f'{ds} set [find where type=FWD name="{d}"] {params} }}'
        )
    lines.append(f'{ds} remove [find where type=FWD comment="{STALE_COMMENT}"]')
    return "\n".join(lines) + "\n"


def main() -> int:
    try:
        domains = read_domains(SRC)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    if not domains:
        print(f"{SRC.name}: no domains", file=sys.stderr)
        return 1
    kept, dropped = drop_covered(domains)
    for d in dropped:
        print(f"skip {d}: covered by a parent domain")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render(kept), encoding="utf-8")
    print(f"dns: {len(kept)} domains -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
